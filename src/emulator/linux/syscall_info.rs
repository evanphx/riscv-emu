/// Syscall information for ktrace.
pub struct SyscallInfo {
    /// Number of arguments, or -1 if unknown.
    pub argc: i32,
    /// Argument formats: 'i' signed, 'p' pointer (hex), 'u' unsigned.
    pub format: &'static str,
    pub name: &'static str,
}

const fn s(argc: i32, format: &'static str, name: &'static str) -> SyscallInfo {
    SyscallInfo { argc, format, name }
}

